new_section = r'''### 2.4 外部组卡约束与内部战斗逻辑：正常玩家不能构造“全 SSSR 卡组”

这一层必须区分“玩家在界面上能配置什么”和“战斗代码拿到一个Loadout以后怎样运行”。前者是**产品外部约束**，后者是**实际战斗逻辑**。两者共同决定正常对局，但不能互相替代解释。

#### 2.4.1 外部设置规则：卡组编辑器强制保留R / SR / SSR

当前客户端本地化表存在专门提示键：

```text
CantEquipCardTip = 卡组必须包含至少1张{0}卡牌
```

结合实际卡组编辑表现，`{0}`会对应玩家看到的不同稀有度类别。正常玩家至少必须保留：

|玩家看到的颜色|内部稀有度|正常卡组最低数量|
|---|---|---:|
|绿色|R|至少1张|
|蓝色|SR|至少1张|
|紫色|SSR|至少1张|
|金色|SSSR|当前没有发现“至少1张”的同类要求|

组卡界面对应`UIModuleO.CardDeckChangePanel`。当前恢复到的关键方法包括`ChangeEquipCard(int nowCardDeckIndex)`、`UpdateCardDeck(...)`和`UpdateShowCardTypeCountUI(...)`，说明这个限制属于卡组编辑/更新链。`CantEquipCardTip_GoldMine = 不要放弃金矿！`还表明同一界面存在其他组卡合法性约束，但当前证据不足以把所有外部约束都归纳成同一种稀有度规则。

因此，对**正常玩家路径**而言，“非空战斗牌组全部由SSSR组成”不是一个合法的UI配置。之前把“全SSSR卡组”作为正常实战边界是不准确的，应该降级为异常、调试、旧数据或其他绕过正常组卡界面的理论输入。

#### 2.4.2 战斗内部规则：不会因为外部最低配卡要求而改写四档概率

外部卡组限制并不意味着战斗内部把50 / 100格的概率重新设计成“保证抽到牌组里已有的稀有度”。当前主链仍然是：

```text
普通格确定价格档位
→ 按GlobalHexInfo抽R / SR / SSR / SSSR / 空
→ 按抽中的稀有度筛选当前战斗Loadout中的合法候选
→ 选择具体建筑并保存隐藏结果
→ 点击时通常读取该隐藏结果
→ 缺失或无法映射时才进入后续回退
```

例如50金币一星格仍然按74 / 20 / 5 / 1抽R / SR / SSR / SSSR；100金币二星格仍然按50 / 40 / 8 / 2抽。UI强制玩家至少带一张R、一张SR、一张SSR，主要作用是让正常牌组更不容易出现“抽到了某个低稀有度，但整个牌组完全没有这个稀有度”的极端空候选情况，而不是改变第二层随机本身。

这也是理解产品设计的一条重要线索：**外部组卡规则在为内部随机系统提供输入前提，内部随机系统本身仍按自己的概率和候选规则运行。**

#### 2.4.3 “至少各一张”也不等于任何格子都一定有候选

这里不能进一步推成“正常卡组永远不会发生候选为空”。第三层还有`hexType`、问号格排除金矿/防御、固定用途、金矿额度等筛选。玩家虽然至少拥有一张R、一张SR、一张SSR，但某个具体稀有度的那一张卡可能并不符合当前格子的类型或其他限制，所以某个具体格子仍可能出现目标稀有度下没有合法候选的情况。

因此，`SelectCardForCellArchitecture`失败后再进入`SelectCardForHex`等回退路径依然是有意义的运行时防护，不能因为UI已经做了最低配卡限制就认为这些fallback永远不可达。

#### 2.4.4 异常/绕过UI的Loadout：全 SSSR 仍是底层可分析的理论边界

如果通过调试、回放、旧数据、异常载荷或其他方式让战斗层收到一个“非空且全部是SSSR”的Loadout，那么之前恢复出的底层边界仍成立：初始化阶段的第二层概率表不会自动改成100% SSSR；如果先抽到R / SR / SSR但第三层没有对应候选，点击阶段可能因为隐藏建筑缺失或无法映射而进入回退，最终从当前合法卡中落到SSSR。

```text
异常/绕过UI的全SSSR Loadout
→ 50 / 100格仍按原概率抽内部稀有度
→ 例如先抽到R或SR
→ 当前Loadout没有对应稀有度候选
→ 初始化具体建筑缺失或无法匹配
→ 点击阶段进入fallback
→ 当前合法候选只有SSSR
→ 最终可能得到SSSR
```

前几次低价翻格的`TryApplyFirstThreeCheapOpenReroll`也不能凭空生成玩家没有的R卡。它会尝试通过`SelectFirstThreeRCardWithoutGoldMine(playerId)`从玩家自己的战斗牌组寻找R候选；异常Loadout如果完全没有R，降级替换仍可能失败。

但这只能写成**底层异常输入下的代码边界**，不能再写成“玩家可以通过全SSSR组卡穿透50 / 100格概率”的正常策略。

#### 2.4.5 战斗层还有Loadout校验，但当前不能证明它重复执行同一条稀有度规则

BattleCore中存在`PlayerBattleLoadoutValidator.ValidateCards(...)`，说明战斗入口还会对载入卡牌做独立合法性检查。当前恢复的函数体更像是在验证卡牌ID、配置引用等载入合法性；目前没有足够证据确认它还会再次检查“R / SR / SSR至少各1张”。

所以现阶段应把规则分层写成：

|层级|已确认规则|当前证据边界|
|---|---|---|
|卡组编辑UI|正常玩家至少保留1张R、1张SR、1张SSR|已由实测与`CantEquipCardTip`互相印证|
|战斗初始化|仍按地块档位的原始稀有度权重抽取|不会因为UI最低配卡规则而自动改权重|
|第三层候选|按抽中稀有度、`hexType`和特殊限制筛当前Loadout|即使各稀有度至少1张，也可能因类型不匹配而局部无候选|
|点击fallback|隐藏建筑缺失/无法匹配时存在回退选卡|用于处理局部无候选和异常状态|
|BattleCore载入校验|存在`ValidateCards(...)`|当前不能证明它重复强制R/SR/SSR各1张|
|全SSSR Loadout|正常UI不可配置|只保留为调试/异常/绕过UI输入的理论边界|

因此，后续分析实战出卡率时应优先采用**正常玩家合法卡组**作为样本空间；只有专门研究容错、调试入口或异常载荷时，才使用“全SSSR”等越过外部组卡规则的极端输入。

'''
